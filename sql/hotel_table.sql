-- 酒店信息表
USE travel_rag;

CREATE TABLE IF NOT EXISTS hotel_rooms (
    id INT AUTO_INCREMENT PRIMARY KEY COMMENT '主键',
    hotel_name VARCHAR(100) NOT NULL COMMENT '酒店名称',
    city VARCHAR(50) NOT NULL COMMENT '所在城市',
    district VARCHAR(50) COMMENT '所在区域',
    address VARCHAR(200) COMMENT '酒店地址',
    room_type VARCHAR(50) NOT NULL COMMENT '房型（如：大床房、双床房、豪华套房）',
    bed_type VARCHAR(30) COMMENT '床型（如：大床、双床、单人床）',
    price DECIMAL(10, 2) NOT NULL COMMENT '每晚价格',
    total_rooms INT NOT NULL COMMENT '总房间数',
    remaining_rooms INT NOT NULL COMMENT '剩余房间数',
    check_in_time TIME DEFAULT '14:00:00' COMMENT '最早入住时间',
    check_out_time TIME DEFAULT '12:00:00' COMMENT '最晚退房时间',
    rating DECIMAL(2, 1) DEFAULT 5.0 COMMENT '酒店评分（1.0-5.0）',
    has_wifi TINYINT(1) DEFAULT 1 COMMENT '是否有WiFi',
    has_breakfast TINYINT(1) DEFAULT 1 COMMENT '是否含早餐',
    has_parking TINYINT(1) DEFAULT 0 COMMENT '是否有停车场',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    UNIQUE KEY unique_hotel_room (hotel_name, room_type)
) ENGINE=INNODB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='酒店房间信息表';

