# 全量城市列表（长名称优先，避免长子串被短名称抢先匹配）
ALL_CITIES: list[str] = sorted(
    {city for cities in PROVINCE_CITIES.values() for city in cities},
    key=lambda name: (-len(name), name),
)


def get_all_cities() -> list[str]:
    """返回全量城市列表副本。"""
    return list(ALL_CITIES)


def get_cities_by_province(province: str) -> list[str]:
    """按省级行政区名称返回城市列表，支持省/市/自治区简称。"""
    province = (province or "").strip()
    for name, cities in PROVINCE_CITIES.items():
        if name == province or name.startswith(province):
            return list(cities)
    return []


def detect_city(text: str) -> str | None:
    """从自然语言中识别第一个城市名，避免把“吉林省”误判为城市“吉林”。"""
    if not text:
        return None
    for city in ALL_CITIES:
        if re.search(re.escape(city) + r"(?!省)", text):
            return city
    return None


def expand_province_to_capital(text: str) -> str:
    """把省份名替换为省会/首府城市，便于识别出发与目的地。"""
    for name, cities in PROVINCE_CITIES.items():
        short = name.rstrip("省市自治区特别行政区")
        if short and short in text and cities:
            text = text.replace(short, cities[0], 1)
    return text
